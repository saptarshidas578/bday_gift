const uint8_t* getFont5x7(char c) {
    if (c == '\x01' || c == '<') return GLYPH_HEART;
    if (c == '\x02' || c == '*') return GLYPH_STAR;
    if (c == '\x03' || c == '^') return GLYPH_SMILE;
    if (c >= 'a' && c <= 'z') c -= 32; // Uppercase
    if (c >= 33 && c <= 90) return ASCII_TABLE[c - 33];
    return GLYPH_SPACE;
}

void drawSyncNeededGlyph(uint32_t now) {
    matrixClear();
    // Blinking antenna/clock icon (blinks every 500ms)
    bool on = ((now / 500) % 2) == 0;
    if (on) {
        CRGB amber = CRGB(255, 140, 0);
        // Question mark / Clock icon glyph centered on 10x10
        matrixSetPixel(4, 1, amber);
        matrixSetPixel(5, 1, amber);
        matrixSetPixel(3, 2, amber);
        matrixSetPixel(6, 2, amber);
        matrixSetPixel(5, 3, amber);
        matrixSetPixel(4, 4, amber);
        matrixSetPixel(4, 5, amber);
        matrixSetPixel(4, 7, amber); // Dot
    }
}
